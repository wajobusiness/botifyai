    private function getWorkspace(Request $request): ?Workspace
    {
        $user = $request->user();
        if (! $user) {
            return null;
        }

        if (! empty($user->workspace_id)) {
            $ws = Workspace::find($user->workspace_id);
            if ($ws) {
                return $ws;
            }
        }

        if (! empty($user->current_workspace_id)) {
            $ws = Workspace::find($user->current_workspace_id);
            if ($ws) {
                return $ws;
            }
        }

        try {
            $ws = $user->workspaces()->first();
            if ($ws) {
                return $ws;
            }
        } catch (\Throwable) {
            // ignore
        }

        if (! empty($user->client_id)) {
            $ws = Workspace::where('client_id', $user->client_id)->first();
            if ($ws) {
                return $ws;
            }
        }

        return Workspace::first();
    }

    /**
     * Try to auto-start the Node.js WhatsApp Gateway service if it is offline.
     */
    private static function tryAutoStartGateway(): void
    {
        try {
            $serverPath = base_path('whatsapp-gateway/server.js');
            if (! file_exists($serverPath)) {
                return;
            }

            // Look for node binary in standard paths
            $nodeBin = null;
            $candidates = [
                '/usr/local/bin/node',
                '/usr/bin/node',
                '/opt/homebrew/bin/node',
                'node',
            ];

            foreach ($candidates as $cand) {
                $check = @shell_exec("which {$cand} 2>/dev/null") ?? @shell_exec("{$cand} -v 2>/dev/null");
                if ($check && str_contains(trim($check), 'v')) {
                    $nodeBin = $cand;
                    break;
                }
            }

            $nodeBin = $nodeBin ?: 'node';
            $logPath = storage_path('logs/whatsapp-gateway.log');

            // Launch detached background daemon process
            @exec("nohup {$nodeBin} " . escapeshellarg($serverPath) . " >> " . escapeshellarg($logPath) . " 2>&1 &");
        } catch (\Throwable $e) {
            Log::warning('tryAutoStartGateway failed: ' . $e->getMessage());
        }
    }

    /**
     * List all linked device sessions for the current workspace.
     */
    public function index(Request $request): JsonResponse
    {
        try {
            WhatsappSchemaProvisioner::ensureTablesExist();
            $workspace = $this->getWorkspace($request);
            if (! $workspace) {
                return response()->json(['error' => 'No active workspace.'], 404);
            }

            $sessions = WhatsappDeviceSession::where('workspace_id', $workspace->id)
                ->with('channelAccount')
                ->orderByDesc('updated_at')
                ->get();

            return response()->json([
                'success' => true,
                'sessions' => $sessions,
                'gateway_available' => WhatsappGatewayClient::isAvailable(),
            ]);
        } catch (\Throwable $e) {
            Log::error('WhatsappDevicePairingController::index error: ' . $e->getMessage());
            return response()->json(['success' => false, 'error' => $e->getMessage()], 500);
        }
    }

    /**
     * Request an authentic 8-digit mobile pairing code generated by WhatsApp servers through Baileys.
     */
    public function requestPairing(Request $request): JsonResponse
    {
        try {
            WhatsappSchemaProvisioner::ensureTablesExist();
            $workspace = $this->getWorkspace($request);
            if (! $workspace) {
                return response()->json(['message' => 'No active workspace found.'], 404);
            }

            // 1. Enforce Entitlement: Linked Devices feature toggle in active plan
            if (! EntitlementService::canAccess($workspace, 'whatsapp_linked_devices')) {
                return response()->json([
                    'message' => 'Personal WhatsApp / Linked Devices connection is not included in your current subscription plan. Please upgrade to link WhatsApp phone numbers.',
                    'code' => 'ENTITLEMENT_REQUIRED',
                ], 403);
            }

            // 2. Enforce Limit: Max connected WhatsApp accounts cap
            if (EntitlementService::hasReachedLimit($workspace, 'max_whatsapp_accounts')) {
                return response()->json([
                    'message' => 'You have reached the maximum allowed WhatsApp accounts for your subscription plan. Please upgrade your plan to connect more numbers.',
                    'code' => 'LIMIT_REACHED',
                ], 403);
            }

            $validated = $request->validate([
                'phone_number'    => ['required', 'string', 'min:7', 'max:25'],
                'name'            => ['nullable', 'string', 'max:128'],
                'connection_type' => ['nullable', 'string', 'in:pairing_code,qr_code,coexistence'],
            ]);

            // Normalize phone number (strip whitespace, dashes, plus, parentheses)
            $cleanPhone = preg_replace('/[^0-9]/', '', $validated['phone_number']);
            if (strlen($cleanPhone) < 7) {
                return response()->json(['message' => 'Please provide a valid international phone number with country code.'], 422);
            }

            $connectionType = $validated['connection_type'] ?? 'pairing_code';
            $displayName = ! empty($validated['name'])
                ? trim($validated['name'])
                : 'WhatsApp (+' . substr($cleanPhone, 0, 3) . '...' . substr($cleanPhone, -4) . ')';

            // Check if a session already exists for this number in this workspace
            $session = WhatsappDeviceSession::where('workspace_id', $workspace->id)
                ->where('phone_number', $cleanPhone)
                ->first();

            if (! $session) {
                $session = WhatsappDeviceSession::create([
                    'workspace_id'      => $workspace->id,
                    'session_uid'       => 'wds_' . Str::random(24),
                    'name'              => $displayName,
                    'phone_number'      => $cleanPhone,
                    'connection_type'   => $connectionType,
                    'connection_status' => 'pairing',
                ]);
            } else {
                $session->update([
                    'name'              => $displayName,
                    'connection_type'   => $connectionType,
                    'connection_status' => 'pairing',
                ]);
            }

            // 3. Ensure WhatsApp Gateway service is running
            if (! WhatsappGatewayClient::isAvailable()) {
                self::tryAutoStartGateway();
                usleep(800000); // 0.8s
            }

            if (! WhatsappGatewayClient::isAvailable()) {
                return response()->json([
                    'success' => false,
                    'code'    => 'GATEWAY_OFFLINE',
                    'message' => 'WhatsApp Gateway daemon is currently offline. Please start it on your server using: "php artisan whatsapp:gateway:start" or "node whatsapp-gateway/server.js"',
                ], 503);
            }

            // 4. Request authentic WhatsApp cryptographic pairing code or QR code from the Baileys gateway socket
            if ($connectionType === 'qr_code') {
                $gatewayResp = WhatsappGatewayClient::requestQr(
                    $session->session_uid,
                    $displayName
                );

                if (! ($gatewayResp['success'] ?? false)) {
                    $errMsg = $gatewayResp['message'] ?? 'Could not generate QR code from WhatsApp servers.';
                    return response()->json(['success' => false, 'message' => $errMsg], 502);
                }

                $qrRaw = $gatewayResp['qr_raw'] ?? null;
                $session->update([
                    'qr_raw'            => $qrRaw,
                    'connection_status' => 'pairing',
                ]);

                return response()->json([
                    'success'            => true,
                    'session_uid'        => $session->session_uid,
                    'connection_type'    => 'qr_code',
                    'qr_raw'             => $qrRaw,
                    'expires_in_seconds' => 60,
                ]);
            }

            $gatewayResp = WhatsappGatewayClient::requestPairingCode(
                $session->session_uid,
                $cleanPhone,
                $displayName
            );

            if (! ($gatewayResp['success'] ?? false)) {
                $errMsg = $gatewayResp['message'] ?? 'Could not generate pairing code from WhatsApp servers.';
                $session->update([
                    'connection_status' => 'failed',
                    'error_message'     => $errMsg,
                ]);

                return response()->json([
                    'success' => false,
                    'message' => $errMsg,
                ], 502);
            }

            $pairingCode = $gatewayResp['pairing_code'] ?? null;
            $expiresInSeconds = $gatewayResp['expires_in_seconds'] ?? 160;
            $expiresAt = now()->addSeconds($expiresInSeconds);

            $session->update([
                'pairing_code'            => $pairingCode,
                'pairing_code_expires_at' => $expiresAt,
                'connection_status'       => 'pairing',
                'error_message'           => null,
            ]);

            return response()->json([
                'success'            => true,
                'session_uid'        => $session->session_uid,
                'pairing_code'       => $pairingCode,
                'phone_number'       => '+' . $cleanPhone,
                'connection_type'    => $connectionType,
                'expires_at'         => $expiresAt->toIso8601String(),
                'expires_in_seconds' => $expiresInSeconds,
                'instructions'       => $gatewayResp['instructions'] ?? [
                    '1. Open WhatsApp on your phone.',
                    '2. Tap Settings (iOS) or Menu (⋮) on Android.',
                    '3. Tap "Linked Devices" then "Link a Device".',
                    '4. Select "Link with phone number instead".',
                    '5. Enter the 8-character code shown above.',
                ],
            ]);
        } catch (\Illuminate\Validation\ValidationException $ve) {
            return response()->json(['message' => $ve->getMessage(), 'errors' => $ve->errors()], 422);
        } catch (\Throwable $e) {
            Log::error('WhatsappDevicePairingController::requestPairing error', [
                'message' => $e->getMessage(),
                'trace'   => $e->getTraceAsString(),
            ]);

            return response()->json([
                'success' => false,
                'message' => 'Pairing error: ' . $e->getMessage(),
            ], 500);
        }
    }

    /**
     * Poll the pairing status of a device session.
     */
    public function status(Request $request, string $sessionUid): JsonResponse
    {
        try {
            WhatsappSchemaProvisioner::ensureTablesExist();
            $workspace = $this->getWorkspace($request);
            if (! $workspace) {
                return response()->json(['message' => 'Unauthorized.'], 401);
            }

            $session = WhatsappDeviceSession::where('workspace_id', $workspace->id)
                ->where('session_uid', $sessionUid)
                ->with('channelAccount')
                ->first();

            if (! $session) {
                return response()->json(['message' => 'Device session not found.'], 404);
            }

            // If session is currently in pairing state, poll the Gateway socket for live status
            if ($session->connection_status === 'pairing') {
                $gwStatus = WhatsappGatewayClient::getStatus($sessionUid);
                if (($gwStatus['status'] ?? '') === 'connected') {
                    $phone = $session->phone_number ?: preg_replace('/[^0-9]/', '', $gwStatus['phone_number'] ?? '');
                    if ($phone) {
                        $session->markConnected($phone, $session->name, 'whatsapp');
                        $session->refresh();
                    }
                } elseif ($session->isPairingExpired()) {
                    $session->update([
                        'connection_status' => 'failed',
                        'error_message'     => 'Pairing code expired. Please request a new code.',
                    ]);
                }
            }

            return response()->json([
                'success'            => true,
                'session_uid'        => $session->session_uid,
                'status'             => $session->connection_status,
                'phone_number'       => $session->phone_number ? '+' . $session->phone_number : null,
                'name'               => $session->name,
                'push_name'          => $session->push_name,
                'platform'           => $session->platform,
                'is_business'        => (bool) $session->is_business,
                'error_message'      => $session->error_message,
                'channel_account_id' => $session->channel_account_id,
                'paired_at'          => $session->paired_at?->toIso8601String(),
                'last_active_at'     => $session->last_active_at?->toIso8601String(),
            ]);
        } catch (\Throwable $e) {
            Log::error('WhatsappDevicePairingController::status error: ' . $e->getMessage());
            return response()->json(['success' => false, 'message' => $e->getMessage()], 500);
        }
    }

    /**
     * Complete / confirm pairing manually.
     */
    public function confirm(Request $request, string $sessionUid): JsonResponse
    {
        try {
            WhatsappSchemaProvisioner::ensureTablesExist();
            $workspace = $this->getWorkspace($request);
            if (! $workspace) {
                return response()->json(['message' => 'Unauthorized.'], 401);
            }

            $session = WhatsappDeviceSession::where('workspace_id', $workspace->id)
                ->where('session_uid', $sessionUid)
                ->first();

            if (! $session) {
                return response()->json(['message' => 'Device session not found.'], 404);
            }

            $pushName = $request->input('push_name', $session->name);
            $platform = $request->input('platform', 'whatsapp');

            $account = $session->markConnected(
                phoneNumber: $session->phone_number,
                pushName: $pushName,
                platform: $platform
            );

            return response()->json([
                'success'            => true,
                'message'            => 'WhatsApp device successfully linked and ready for messaging!',
                'session'            => $session->fresh(),
                'channel_account_id' => $account->id,
            ]);
        } catch (\Throwable $e) {
            Log::error('WhatsappDevicePairingController::confirm error: ' . $e->getMessage());
            return response()->json(['success' => false, 'message' => $e->getMessage()], 500);
        }
    }

    /**
     * Inbound message webhook from Baileys Gateway.
     */
    public function inboundWebhook(Request $request): JsonResponse
    {
        $secret = $request->header('X-Gateway-Secret');
        $expectedSecret = (string) config('services.whatsapp_gateway.secret', env('WHATSAPP_GATEWAY_SECRET', config('app.key', 'botifyai-whatsapp-secret-key')));

        if ($expectedSecret && $secret !== $expectedSecret) {
            return response()->json(['error' => 'Unauthorized'], 401);
        }

        $sessionUid = $request->input('session_uid');
        $fromPhone = preg_replace('/[^0-9]/', '', (string) $request->input('from'));
        $body = (string) ($request->input('text') ?? '');
        $messageId = (string) ($request->input('message_id') ?? ('wds_msg_' . Str::random(16)));
        $pushName = $request->input('push_name');

        if (! $sessionUid || ! $fromPhone) {
            return response()->json(['error' => 'Missing session_uid or from phone'], 400);
        }

        $session = WhatsappDeviceSession::where('session_uid', $sessionUid)->first();
        if (! $session) {
            return response()->json(['error' => 'Session not found'], 404);
        }

        $workspaceId = (int) $session->workspace_id;
        $channelAccount = $session->channelAccount;

        // Upsert Contact
        $contact = Contact::updateOrCreate(
            [
                'workspace_id' => $workspaceId,
                'phone_e164'   => '+' . $fromPhone,
            ],
            [
                'name'             => $pushName ?: ('WhatsApp User (+' . $fromPhone . ')'),
                'opt_in_whatsapp'  => true,
                'source'           => 'whatsapp_linked_device',
            ]
        );

        // Upsert Conversation
        $conversation = Conversation::firstOrCreate(
            [
                'workspace_id'       => $workspaceId,
                'contact_id'         => $contact->id,
                'channel_account_id' => $channelAccount?->id,
            ],
            [
                'status'             => 'open',
                'external_thread_id' => $fromPhone,
            ]
        );

        // Create Message
        $message = Message::create([
            'conversation_id'     => $conversation->id,
            'direction'           => 'in',
            'channel'             => 'whatsapp',
            'type'                => 'text',
            'payload'             => $request->all(),
            'body'                => $body,
            'status'              => 'delivered',
            'provider_message_id' => $messageId,
            'sent_by'             => 'human',
            'sent_at'             => now(),
        ]);

        $conversation->update([
            'last_message_at'   => $message->sent_at,
            'status'            => 'open',
            'unread_count'      => $conversation->unread_count + 1,
            'last_inbound_at'   => $message->sent_at,
        ]);

        // Fire event so AI chatbots and Automations process this incoming message
        try {
            MessageReceived::dispatch($message);
        } catch (\Throwable $e) {
            Log::warning('Inbound message event dispatch error: ' . $e->getMessage());
        }

        return response()->json(['success' => true, 'message_id' => $message->id]);
    }

    /**
     * Connected webhook from Baileys Gateway when socket opens.
     */
