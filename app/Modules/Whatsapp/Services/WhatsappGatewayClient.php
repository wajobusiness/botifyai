<?php

namespace App\Modules\Whatsapp\Services;

use Illuminate\Support\Facades\Http;
use Illuminate\Support\Facades\Log;

class WhatsappGatewayClient
{
    private static function baseUrl(): string
    {
        return rtrim(config('services.whatsapp_gateway.url', env('WHATSAPP_GATEWAY_URL', 'http://127.0.0.1:3100')), '/');
    }

    private static function secret(): string
    {
        return (string) config('services.whatsapp_gateway.secret', env('WHATSAPP_GATEWAY_SECRET', config('app.key', 'botifyai-whatsapp-secret-key')));
    }

    /**
     * Check if the background WhatsApp Baileys gateway service is alive and healthy.
     */
    public static function isAvailable(): bool
    {
        try {
            $res = Http::timeout(3)->get(self::baseUrl() . '/health');
            return $res->successful() && ($res->json('status') === 'healthy');
        } catch (\Throwable) {
            return false;
        }
    }

    /**
     * Request a real 8-character pairing code generated by WhatsApp servers through the Baileys socket.
     */
    public static function requestPairingCode(string $sessionUid, string $phoneNumber, ?string $name = null): array
    {
        try {
            $response = Http::timeout(25)
                ->withHeaders([
                    'X-Gateway-Secret' => self::secret(),
                    'Accept'           => 'application/json',
                ])
                ->post(self::baseUrl() . '/sessions/request-pairing', [
                    'session_id'   => $sessionUid,
                    'phone_number' => $phoneNumber,
                    'name'         => $name,
                ]);

            if ($response->successful()) {
                return $response->json();
            }

            $errorMsg = $response->json('message') ?? 'Failed to request pairing code from WhatsApp Gateway (HTTP ' . $response->status() . ').';
            return [
                'success' => false,
                'message' => $errorMsg,
            ];
        } catch (\Throwable $e) {
            Log::error('WhatsappGatewayClient::requestPairingCode connection failed', ['error' => $e->getMessage()]);
            return [
                'success' => false,
                'message' => 'WhatsApp Gateway is unreachable. Please ensure the gateway service is running on ' . self::baseUrl() . '. (' . $e->getMessage() . ')',
            ];
        }
    }

    /**
     * Fetch live connection status of a session from the Gateway.
     */
    public static function getStatus(string $sessionUid): array
    {
        try {
            $response = Http::timeout(4)
                ->withHeaders([
                    'X-Gateway-Secret' => self::secret(),
                    'Accept'           => 'application/json',
                ])
                ->get(self::baseUrl() . '/sessions/' . urlencode($sessionUid) . '/status');

            if ($response->successful()) {
                return $response->json();
            }

            return ['success' => false, 'status' => 'disconnected'];
        } catch (\Throwable) {
            return ['success' => false, 'status' => 'disconnected'];
        }
    }

    /**
     * Send an outbound WhatsApp text or media message through the linked session.
     */
    public static function sendMessage(string $sessionUid, string $to, string $body): array
    {
        try {
            $response = Http::timeout(15)
                ->withHeaders([
                    'X-Gateway-Secret' => self::secret(),
                    'Accept'           => 'application/json',
                ])
                ->post(self::baseUrl() . '/sessions/send-message', [
                    'session_id' => $sessionUid,
                    'to'         => $to,
                    'body'       => $body,
                ]);

            return $response->json() ?? ['success' => false, 'message' => 'Empty response from gateway.'];
        } catch (\Throwable $e) {
            Log::error('WhatsappGatewayClient::sendMessage error', ['session' => $sessionUid, 'error' => $e->getMessage()]);
            return [
                'success' => false,
                'message' => 'Failed to send WhatsApp message via linked device gateway: ' . $e->getMessage(),
            ];
        }
    }

    /**
     * Permanently delete and disconnect a session on the Gateway.
     */
    public static function deleteSession(string $sessionUid): bool
    {
        try {
            $response = Http::timeout(5)
                ->withHeaders([
                    'X-Gateway-Secret' => self::secret(),
                    'Accept'           => 'application/json',
                ])
                ->delete(self::baseUrl() . '/sessions/' . urlencode($sessionUid));

            return $response->successful();
        } catch (\Throwable) {
            return false;
        }
    }
}
